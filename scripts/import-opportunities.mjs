#!/usr/bin/env node
// Import the opportunities catalog (olympiads, competitions, research programs,
// scholarships) from ONE table → lib/competitions.generated.js.
//
//   npm run data:opportunities                         # from data/opportunities.csv
//   OPPORTUNITIES_CSV_URL=<url> npm run data:opportunities   # from Google Sheets
//
// Google Sheets: File → Share → Publish to web → the sheet → CSV → copy link.
// Columns (first row = header, order doesn't matter):
//   id, name, category, type, level, subject, cost, difficulty, selectivity,
//   season, deadline_month, deadline_label, link, blurb, verified_on
// Every row is validated; bad rows are reported with their line number and
// skipped, so one typo never breaks the site. Rows in the table override the
// hand-written core entries with the same id.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LOCAL = path.join(ROOT, 'data/opportunities.csv');
const OUT = path.join(ROOT, 'lib/competitions.generated.js');

const ENUMS = {
  category: ['Math', 'Science', 'Computer Science', 'Research', 'Business', 'Writing & Arts', 'Leadership', 'Scholarship', 'Summer Program'],
  type: ['olympiad', 'competition', 'research', 'program', 'scholarship'],
  level: ['international', 'national', 'regional', 'online'],
  cost: ['free', 'paid', 'stipend'],
};
const REQUIRED = ['id', 'name', 'category', 'type', 'level', 'cost', 'blurb'];

// RFC 4180 CSV parser (quotes, escaped quotes, newlines inside quotes).
function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (ch === '"') q = false;
      else cell += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') {
      row.push(cell);
      cell = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(cell);
      rows.push(row);
      row = [];
      cell = '';
    } else cell += ch;
  }
  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }
  return rows.filter((r) => r.some((c) => c.trim()));
}

async function load() {
  const url = process.env.OPPORTUNITIES_CSV_URL;
  if (url) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`Could not fetch the sheet (${res.status}). Is it published to the web as CSV?`);
    return { text: await res.text(), from: 'Google Sheet' };
  }
  return { text: fs.readFileSync(LOCAL, 'utf8'), from: 'data/opportunities.csv' };
}

function validate(r) {
  const errors = [];
  for (const k of REQUIRED) if (!r[k]) errors.push(`missing ${k}`);
  if (r.id && !/^[a-z0-9-]+$/.test(r.id)) errors.push('id must be lowercase-with-dashes');
  for (const [k, allowed] of Object.entries(ENUMS)) if (r[k] && !allowed.includes(r[k])) errors.push(`${k} "${r[k]}" not in ${allowed.join('/')}`);
  if (r.difficulty && !(Number(r.difficulty) >= 1 && Number(r.difficulty) <= 5)) errors.push('difficulty must be 1–5');
  if (r.deadline_month && !(Number(r.deadline_month) >= 1 && Number(r.deadline_month) <= 12)) errors.push('deadline_month must be 1–12');
  if (r.link && !/^https:\/\//.test(r.link)) errors.push('link must start with https://');
  if (r.verified_on && !/^\d{4}-\d{2}-\d{2}$/.test(r.verified_on)) errors.push('verified_on must be YYYY-MM-DD');
  return errors;
}

async function main() {
  const { text, from } = await load();
  const [header, ...lines] = parseCsv(text);
  const cols = header.map((h) => h.trim().toLowerCase());
  const out = [];
  const seen = new Set();
  let bad = 0;
  lines.forEach((cells, i) => {
    const r = Object.fromEntries(cols.map((c, j) => [c, (cells[j] || '').trim()]));
    const errors = validate(r);
    if (seen.has(r.id)) errors.push('duplicate id');
    if (errors.length) {
      bad++;
      console.warn(`  ✗ line ${i + 2} (${r.id || r.name || '?'}): ${errors.join('; ')}`);
      return;
    }
    seen.add(r.id);
    out.push({
      id: r.id,
      name: r.name,
      category: r.category,
      type: r.type,
      level: r.level,
      subject: r.subject || '',
      cost: r.cost,
      difficulty: Number(r.difficulty) || 3,
      selectivity: r.selectivity || '',
      season: r.season || '',
      blurb: r.blurb,
      ...(r.link ? { link: r.link } : {}),
      ...(r.deadline_month ? { deadline: { month: Number(r.deadline_month), label: r.deadline_label || 'Deadline' } } : {}),
      ...(r.verified_on ? { verifiedOn: r.verified_on } : {}),
    });
  });

  const stamp = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(
    OUT,
    `// AUTO-GENERATED by scripts/import-opportunities.mjs from ${from} on ${stamp}.
// Edit the table (data/opportunities.csv or the Google Sheet), not this file.
// \`deadline.month\` is approximate and recurring — always confirm with \`link\`.

export const GENERATED_COMPETITIONS = [
${out.map((c) => `  ${JSON.stringify(c)}`).join(',\n')}
];
`
  );
  console.log(`✓ ${out.length} opportunities → lib/competitions.generated.js${bad ? ` (${bad} rows skipped — fix them above)` : ''}`);
  if (bad) process.exitCode = 1;
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
